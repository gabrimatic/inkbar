import AppKit

/// Pasteboard work that must never lose what the user copied.
@MainActor
enum Clipboard {
    /// Marks Inkbar's own short-lived writes so clipboard managers skip them
    /// (nspasteboard.org convention).
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// Every item and every type on a pasteboard, kept as raw data in the original
    /// type order (apps read the first type they understand, so order matters).
    struct Snapshot {
        let items: [[(type: NSPasteboard.PasteboardType, data: Data)]]
        let changeCount: Int

        var isEmpty: Bool { items.isEmpty }
    }

    static func snapshot(_ pb: NSPasteboard = .general) -> Snapshot {
        let items = (pb.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type: type, data: $0) } }
        }
        return Snapshot(items: items, changeCount: pb.changeCount)
    }

    /// Puts a snapshot back exactly, every item and type. Returns the new change count.
    @discardableResult
    static func restore(_ snapshot: Snapshot, to pb: NSPasteboard = .general) -> Int {
        pb.clearContents()
        let items: [NSPasteboardItem] = snapshot.items.compactMap { types in
            guard !types.isEmpty else { return nil }
            let item = NSPasteboardItem()
            for entry in types { item.setData(entry.data, forType: entry.type) }
            return item
        }
        if !items.isEmpty { pb.writeObjects(items) }
        return pb.changeCount
    }

    /// Copies plain text as the user's own copy: no transient marker, it is meant to stay.
    static func copy(_ text: String, to pb: NSPasteboard = .general) {
        pb.clearContents()
        pb.setString(text, forType: .string)
    }

    /// The clipboard as plain text, for Paste Clean. File copies and images do not count.
    static func plainText(_ pb: NSPasteboard = .general) -> String? {
        let types = pb.types ?? []
        if types.contains(.fileURL) { return nil }
        guard let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        return s
    }

    /// True only when there is real text to paste. A text type holding nothing or only
    /// whitespace (an emptied clipboard some apps leave behind) does not count.
    static func hasPlainText(_ pb: NSPasteboard = .general) -> Bool {
        plainText(pb) != nil
    }

    /// Writes text for a synthetic paste, marked transient.
    static func stage(_ text: String, on pb: NSPasteboard = .general) -> Int {
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: transientType)
        item.setData(Data(), forType: autoGeneratedType)
        pb.writeObjects([item])
        return pb.changeCount
    }
}
